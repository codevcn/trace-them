def get_site_types(platform: str) -> list[str]:
    """Return matching site type keys ('social', 'programming', 'gaming') for a platform."""
    key = (platform or "").strip().casefold()
    types: list[str] = []
    if key in SOCIAL_MEDIA_SITES:
        types.append("social")
    if key in PROGRAMMING_SITES:
        types.append("programming")
    if key in GAMING_SITES:
        types.append("gaming")
    return types
